export function formatPrice(amount) {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount)
}

export function filterProducts(list, filter) {
  if (!filter || filter === 'All') return list
  if (
    filter === 'Dogs' ||
    filter === 'Cats' ||
    filter === 'Birds' ||
    filter === 'Fish' ||
    filter === 'Small Pets'
  ) {
    return list.filter((p) => p.petType === filter)
  }
  return list.filter(
    (p) =>
      p.category === filter ||
      p.subcategory === filter ||
      p.categorySlug === filter ||
      p.subcategorySlug === filter,
  )
}

export function searchProducts(list, query) {
  const q = String(query || '')
    .trim()
    .toLowerCase()
  if (!q) return list
  return list.filter((p) => {
    const keywordHit = (p.keywords || []).some((k) =>
      String(k).toLowerCase().includes(q),
    )
    return (
      keywordHit ||
      [p.name, p.brand, p.category, p.petType, p.subcategory, p.sku, p.description, p.shortDescription]
        .filter(Boolean)
        .some((field) => String(field).toLowerCase().includes(q))
    )
  })
}

export function getProductBySlug(slug) {
  return catalogProducts.find((p) => p.slug === slug) || null
}

export function getProductsByCategorySlug(slug) {
  return catalogProducts.filter(
    (p) =>
      p.categorySlug === slug ||
      p.subcategorySlug === slug ||
      p.petType.toLowerCase().replace(/\s+/g, '-') === slug,
  )
}

export function getProductsByPetType(type) {
  return catalogProducts.filter((p) => p.petType === type)
}
